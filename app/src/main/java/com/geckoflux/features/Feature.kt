package com.geckoflux.features

/**
 * Enumeration of toggleable features in GeckoFlux.
 */
enum class Feature {
    /**
     * uBlock Origin ad-blocking WebExtension.
     */
    UBLOCK_ORIGIN,

    /**
     * Dark theme enforcement via YouTube preference cookie and WebExtension.
     */
    DARK_THEME,

    /**
     * Native swipe-down gesture to exit fullscreen video mode.
     */
    SWIPE_DOWN_EXIT_FULLSCREEN,
}
